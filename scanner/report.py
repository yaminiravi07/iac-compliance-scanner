"""Write scan results to JSON (for machines) and HTML (for people)."""
import json
from dataclasses import asdict
from datetime import datetime
from html import escape


def summarise(findings):
    """Count findings per severity."""
    return {sev: sum(f.severity == sev for f in findings) for sev in ("HIGH", "MEDIUM", "LOW")}


def write_json(findings, target, resource_count, path):
    """Save results as JSON - easy for other tools and pipelines to read."""
    data = {
        "target": target,
        "scanned_at": datetime.now().isoformat(timespec="seconds"),
        "resources_scanned": resource_count,
        "summary": summarise(findings),
        "findings": [asdict(f) for f in findings],
    }
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)


