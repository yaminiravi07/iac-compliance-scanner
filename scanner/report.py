def write_html(findings, target, resource_count, path):
    """Save results as a styled HTML page you can open in any browser."""
    if findings:
        rows = "\n".join(
            f"<tr><td class='badge {f.severity}'>{f.severity}</td><td>{escape(f.rule_id)}</td>"
            f"<td>{escape(f.resource)}<br><small>{escape(f.file)}</small></td>"
            f"<td>{escape(f.message)}</td><td>{escape(f.iso27001)}</td><td>{escape(f.bsi)}</td></tr>"
            for f in findings
        )
        body = ("<table><tr><th>Severity</th><th>Rule</th><th>Resource</th><th>Problem</th>"
                f"<th>ISO 27001</th><th>BSI</th></tr>\n{rows}\n</table>")
    else:
        body = "<p class='ok'>No issues found.</p>"

    counts = summarise(findings)
    html = HTML_TEMPLATE.format(
        target=escape(target), scanned_at=datetime.now().strftime("%Y-%m-%d %H:%M"),
        resource_count=resource_count, total=len(findings),
        high=counts["HIGH"], medium=counts["MEDIUM"], low=counts["LOW"], body=body,
    )
    with open(path, "w", encoding="utf-8") as f:
        f.write(html)